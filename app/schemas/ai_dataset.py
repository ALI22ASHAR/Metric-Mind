from datetime import datetime, timezone
from typing import Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class AIDatasetUnderstanding(BaseModel):
    """
    Structured analytical output generated by the AI Dataset Understanding Agent.
    """
    dataset_id: str = Field(..., description="Target dataset ID")
    domain: str = Field("sales", description="Inferred business domain (e.g. ecommerce, retail, b2b_sales, saas, inventory)")
    business_summary: str = Field(..., description="Executive summary explaining the dataset purpose and contents")
    primary_date_column: Optional[str] = Field(None, description="Recommended primary date/time axis for trend analysis")
    refined_mappings: Dict[str, str] = Field(default_factory=dict, description="Refined semantic concept mappings")
    dimension_hierarchies: List[List[str]] = Field(
        default_factory=list,
        description="Recommended drill-down hierarchies (e.g. [['country', 'state', 'city'], ['category', 'product']])",
    )
    recommended_metrics: List[str] = Field(
        default_factory=list,
        description="High-value business KPIs computable from this dataset (e.g. ['total_revenue', 'profit_margin'])",
    )
    candidate_business_questions: List[str] = Field(
        default_factory=list,
        description="Sample natural language business questions the user can ask about this dataset",
    )
    confidence_score: float = Field(0.95, ge=0.0, le=1.0, description="Confidence score of AI analysis (0.0 to 1.0)")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Analysis timestamp")

    model_config = ConfigDict(from_attributes=True)
